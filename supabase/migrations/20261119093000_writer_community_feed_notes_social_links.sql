create table if not exists public.writer_achievement_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  achievement_id text not null,
  earned_at timestamptz not null default now(),
  constraint writer_achievement_events_user_achievement_unique unique (user_id, achievement_id)
);

alter table public.writer_achievement_events enable row level security;
grant select on public.writer_achievement_events to authenticated;

drop policy if exists writer_achievement_events_select_own on public.writer_achievement_events;
create policy writer_achievement_events_select_own
  on public.writer_achievement_events
  for select to authenticated
  using (user_id = (select auth.uid()));

create or replace function public.sync_writer_achievement_events()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  achievement text;
begin
  if jsonb_typeof(coalesce(new.diary_achievements, '[]'::jsonb)) = 'array' then
    for achievement in
      select jsonb_array_elements_text(coalesce(new.diary_achievements, '[]'::jsonb))
    loop
      if length(trim(achievement)) > 0 then
        insert into public.writer_achievement_events(user_id, achievement_id)
        values (new.user_id, achievement)
        on conflict (user_id, achievement_id) do nothing;
      end if;
    end loop;
  end if;
  return new;
end;
$$;

drop trigger if exists writer_settings_sync_achievement_events on public.writer_settings;
create trigger writer_settings_sync_achievement_events
  after insert or update of diary_achievements on public.writer_settings
  for each row execute function public.sync_writer_achievement_events();

insert into public.writer_achievement_events(user_id, achievement_id, earned_at)
select ws.user_id, achievement_id, coalesce(ws.updated_at, ws.created_at, now())
from public.writer_settings ws
cross join lateral jsonb_array_elements_text(
  case when jsonb_typeof(ws.diary_achievements) = 'array'
    then ws.diary_achievements else '[]'::jsonb end
) as achievement_id
where length(trim(achievement_id)) > 0
on conflict (user_id, achievement_id) do nothing;

create or replace function public.get_writer_achievement_feed()
returns table (
  event_id bigint,
  user_id uuid,
  display_name text,
  avatar_url text,
  social_url text,
  donation_url text,
  achievement_id text,
  earned_at timestamptz
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select
    e.id,
    e.user_id,
    coalesce(p.display_name, 'Автор'),
    p.avatar_url,
    p.social_url,
    p.donation_url,
    e.achievement_id,
    e.earned_at
  from public.writer_achievement_events e
  join public.writer_settings s on s.user_id = e.user_id
  join public.profiles p on p.id = e.user_id
  where (select auth.uid()) is not null
    and e.user_id <> (select auth.uid())
    and s.show_stats_to_mutuals is true
  order by e.earned_at desc, e.id desc
  limit 50;
$$;

revoke all on function public.get_writer_achievement_feed() from public, anon;
grant execute on function public.get_writer_achievement_feed() to authenticated;
